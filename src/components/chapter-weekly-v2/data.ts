export type WeekPlan = {
  week: number;
  book: BookPlan;
  /** פרק בתוך הספר (1..N) */
  chapter: number;
  /** "יהושע י׳" */
  label: string;
  /** "כ״ח בתשרי" */
  dateHeb: string;
  /** תאריך לועזי, ליום-שישי של השבוע */
  date: Date;
};

function hebrewDate(d: Date): string {
  const hd = new HDate(d);
  // hebcal מאיית "חשון"/"סיון"; הכתיב המקובל בלי ניקוד הוא "חשוון"/"סיוון".
  const month = Locale.gettext(hd.getMonthName(), "he-x-NoNikud")
    .replace("חשון", "חשוון")
    .replace("סיון", "סיוון");
  return `${gematriya(hd.getDate())} ב${month}`;
}

export const WEEKS: WeekPlan[] = (() => {
  const [y, m, d] = SEASON.startDateISO.split("-").map(Number);
  return Array.from({ length: SEASON.totalWeeks }, (_, i) => {
    const week = i + 1;
    const book = BOOKS.find((b) => week >= b.weekFrom && week <= b.weekTo) ?? BOOKS[0];
    const chapter = week - book.weekFrom + 1;
    const date = new Date(y, m - 1, d + 7 * i);
    return {
      week,
      book,
      chapter,
      label: `${book.name} ${gematriya(chapter)}`,
      dateHeb: hebrewDate(date),
      date,
    };
  });
})();

