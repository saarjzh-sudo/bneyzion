-- benzi_knowledge — מאגר ידע עובדתי לעוזר בנצי
-- ניתן לעריכה ב-/admin/benzi בלי deploy של קוד
-- שינוי נכנס לתוקף מיד (edge function טוענת ב-runtime)

CREATE TABLE IF NOT EXISTS benzi_knowledge (
  id          TEXT PRIMARY KEY,           -- מפתח קריא לאנוש (למשל "main", "rabbi_yoav", "programs")
  title       TEXT NOT NULL,              -- כותרת קצרה להצגה ב-UI
  content     TEXT NOT NULL,             -- גוף הידע — טקסט חופשי בעברית
  is_active   BOOLEAN NOT NULL DEFAULT true,  -- כיבוי זמני בלי מחיקה
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- RLS: קריאה ציבורית (edge function קוראת בלי auth), כתיבה רק אדמין
ALTER TABLE benzi_knowledge ENABLE ROW LEVEL SECURITY;

CREATE POLICY "benzi_knowledge_public_read"
  ON benzi_knowledge FOR SELECT
  USING (true);

CREATE POLICY "benzi_knowledge_admin_write"
  ON benzi_knowledge FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM user_roles
      WHERE user_id = auth.uid() AND role = 'admin'
    )
  );

